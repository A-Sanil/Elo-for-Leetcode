import { readFile, writeFile } from 'node:fs/promises';

const base = 'https://raw.githubusercontent.com/zerotrac/leetcode_problem_rating/';
const input = process.argv[2];
const ref = process.argv[3] || (input ? 'local snapshot' : 'main');
const payload = input ? await readFile(input, 'utf8') : await (async () => {
  const response = await fetch(base + ref + '/data.json');
  if (!response.ok) throw new Error('Upstream HTTP ' + response.status);
  return response.text();
})();
const rows = JSON.parse(payload);
if (!Array.isArray(rows)) throw new Error('Expected upstream array.');
const valid = rows.filter(row => /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(row.TitleSlug)
  && typeof row.Title === 'string' && Number.isFinite(row.Rating) && row.Rating > 0);
if (valid.length < 100) throw new Error('Unexpectedly small upstream snapshot.');
const problems = Object.fromEntries(valid.sort((a, b) => a.TitleSlug.localeCompare(b.TitleSlug))
  .map(row => [row.TitleSlug, [row.Title, Math.round(row.Rating)]]));
const file = new URL('../extension/data/contest.js', import.meta.url);
const source = { upstream: 'https://github.com/zerotrac/leetcode_problem_rating', ref, problems };
await writeFile(file, '// Generated by scripts/refresh-ratings.mjs. See ZEROTRAC-LICENSE.txt.\n'
  + 'globalThis.LcContest = ' + JSON.stringify(source) + ';\n');
console.log('Wrote ' + Object.keys(problems).length + ' contest ratings (' + ref + ').');
